function buildShowcaseTrace(seed: ShowcaseSeed, lineCount: number, contrastBody: number): AgentTraceStep[] {
  const sigLabel = SIGNATURE_MOTIONS[seed.blueprint.signature].label;
  return [
    {
      id: `${seed.id}-t1`,
      kind: 'thought',
      label: `Phân tích bài toán "${seed.title}" (${seed.categoryLabel})`,
      detail: `Đóng vai ${seed.authorLabel} · ${seed.blueprint.profile.sections.length} phần nội dung.`,
      status: 'done',
    },
    {
      id: `${seed.id}-t2`,
      kind: 'vault_search',
      label: `Đã tra 5.994 mẫu kho tài nguyên (chọn ${seed.blueprint.sourceRefs.length} khối)`,
      detail: seed.blueprint.sourceRefs.map((r: MatchedVaultResource) => `${r.title} (${r.library})`).join(' · '),
      status: 'done',
    },
    {
      id: `${seed.id}-t3`,
      kind: 'file_create',
      label: 'Created index.html',
      added: lineCount,
      removed: 0,
      status: 'done',
    },
    {
      id: `${seed.id}-t4`,
      kind: 'check',
      label: `Kiểm tra tương phản ${contrastBody}:1 · ${sigLabel}`,
      detail: 'Sạch tiếng Việt, không tràn ngang 390px và có nhánh prefers-reduced-motion.',
      status: 'done',
    },
  ];
}

export const AGENT_SHOWCASE_BLUEPRINTS: Record<string, ComposerBlueprint> = {};

export const AGENT_SHOWCASE_15: AgentShowcaseProduct[] = SHOWCASE_SEEDS.map((seed) => {
  const { html, audit } = renderBlueprintToHtml(seed.blueprint);
  AGENT_SHOWCASE_BLUEPRINTS[seed.id] = seed.blueprint;
  const lineCount = html.split('\n').length;
  return {
    id: seed.id,
    slug: seed.slug,
    title: seed.title,
    subtitle: seed.subtitle,
    category: seed.category,
    categoryLabel: seed.categoryLabel,
    authorLabel: seed.authorLabel,
    profile: seed.blueprint.profile,
    userPrompt: seed.userPrompt,
    motionSignature: SIGNATURE_MOTIONS[seed.blueprint.signature].label,
    sourceRefs: seed.blueprint.sourceRefs,
    trace: buildShowcaseTrace(seed, lineCount, audit.contrastBody),
    html,
  };
});

export function getShowcaseBlueprintById(id: string): ComposerBlueprint | null {
  return AGENT_SHOWCASE_BLUEPRINTS[id] ?? null;
}
